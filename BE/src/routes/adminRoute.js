const express = require('express');
const router = express.Router();
const authMiddleware = require('../middleware/authMiddleware');
const { isAdmin } = require('../middleware/isAdminMiddleware');
const {getPendingRecipes,getPendingRecipeDetail,approveRecipe,rejectRecipe,getAllContacts,deleteUser,getAllUsers,getApprovedRecipes,deleteApprovedRecipe,updateApprovedRecipe} = require('../controllers/adminController');
router.get('/pending', authMiddleware, isAdmin, getPendingRecipes);
router.get('/pending/:id', authMiddleware, isAdmin, getPendingRecipeDetail);
router.put('/approve/:id', authMiddleware, isAdmin, approveRecipe);
router.delete('/reject/:id', authMiddleware, isAdmin, rejectRecipe);
router.get('/users/all',authMiddleware, isAdmin, getAllUsers);
router.delete('/users/:id',authMiddleware, isAdmin, deleteUser);
router.get('/contact',authMiddleware, isAdmin, getAllContacts);
router.get('/items', authMiddleware, isAdmin, getApprovedRecipes);
router.delete('/items/:id', authMiddleware, isAdmin, deleteApprovedRecipe);
router.put('/items/:id', authMiddleware, isAdmin, updateApprovedRecipe);
module.exports = router;